// Generates src/i18n/calendar.ts from the platform's CLDR data (node has full ICU), so every
// language gets correct month/weekday names, date order and 12/24-hour clock without native calls.
import fs from 'node:fs';
const LANGS = process.argv.slice(2);
const out = {};
const jan = (m, d = 25) => new Date(2026, m, d, 12);
for (const l of LANGS) {
  const f = (o, d) => new Intl.DateTimeFormat(l, o).format(d);
  const parts = (o, d) => new Intl.DateTimeFormat(l, o).formatToParts(d);
  const months = [...Array(12)].map((_, m) => f({ month: 'long' }, jan(m)));
  const monthsShort = [...Array(12)].map((_, m) => f({ month: 'short' }, jan(m)));
  // the month as it appears next to a day ("5 ноября", "5. Nov."), and the order
  const inDate = (style) => [...Array(12)].map((_, m) => parts({ day: 'numeric', month: style }, jan(m)).find((p) => p.type === 'month').value);
  const pattern = (o) => parts(o, jan(10, 25)).map((p) => (p.type === 'day' ? '{d}' : p.type === 'month' ? '{m}' : p.type === 'year' ? '{y}' : p.value)).join('');
  const sun = new Date(2026, 0, 4, 12);
  const wd = (style) => [...Array(7)].map((_, i) => f({ weekday: style }, new Date(sun.getTime() + i * 86400000)));
  const hc = new Intl.DateTimeFormat(l, { hour: 'numeric' }).resolvedOptions().hourCycle;
  const h12 = hc === 'h12' || hc === 'h11';
  const tp = parts({ hour: 'numeric', minute: '2-digit' }, new Date(2026, 0, 4, 20, 5));
  const am = parts({ hour: 'numeric', minute: '2-digit' }, new Date(2026, 0, 4, 8, 5)).find((p) => p.type === 'dayPeriod')?.value ?? 'AM';
  const pm = tp.find((p) => p.type === 'dayPeriod')?.value ?? 'PM';
  const time = tp.map((p) => (p.type === 'hour' ? '{h}' : p.type === 'minute' ? '{mm}' : p.type === 'dayPeriod' ? '{p}' : p.value)).join('');
  const rtf = new Intl.RelativeTimeFormat(l, { numeric: 'auto' });
  const rel = { now: rtf.format(0, 'second'), ago: rtf.format(-7, 'minute').replace('7', '{n}'), today: rtf.format(0, 'day') };
  out[l] = {
    rel,
    months,
    monthsShort,
    monthsInDate: inDate('long'),
    monthsShortInDate: inDate('short'),
    weekdays: wd('long'),
    weekdaysShort: wd('short'),
    initials: wd('narrow'),
    dm: pattern({ day: 'numeric', month: 'short' }),
    dmy: pattern({ day: 'numeric', month: 'short', year: 'numeric' }),
    dmNum: pattern({ day: 'numeric', month: 'numeric' }).replace('11', '{mn}'),
    h12,
    pad: parts({ hour: 'numeric', minute: '2-digit' }, new Date(2026, 0, 4, 8, 5)).find((p) => p.type === 'hour').value.length === 2,
    am,
    pm,
    time: h12 ? time : time.replace('{p}', '').trim(),
  };
}
const body = `/* Generated by tools/i18n/calendar.mjs from CLDR (do not edit by hand). */
export type Calendar = { rel: { now: string; ago: string; today: string }; months: string[]; monthsShort: string[]; monthsInDate: string[]; monthsShortInDate: string[]; weekdays: string[]; weekdaysShort: string[]; initials: string[]; dm: string; dmy: string; dmNum: string; h12: boolean; pad: boolean; am: string; pm: string; time: string };
export const CALENDAR: Record<string, Calendar> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync('src/i18n/calendar.ts', body.replace(/ | /g, ' '));
