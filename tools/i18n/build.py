#!/usr/bin/env python3
"""
Turns translator output (id → text, see tools/i18n/BRIEF.md) into the app's locale files:
src/i18n/locales/<lang>.json (English text → translation) and src/i18n/locales/index.ts.

    python3 tools/i18n/build.py <work dir with source.json and out/<lang>.json>
"""
import json, os, sys, glob
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
work = sys.argv[1]
src = {x['id']: x['en'] for x in json.load(open(os.path.join(work, 'source.json'), encoding='utf-8'))}
dest = os.path.join(root, 'src', 'i18n', 'locales')
os.makedirs(dest, exist_ok=True)
for path in sorted(glob.glob(os.path.join(work, 'out', '*.json'))):
    name = os.path.basename(path)[:-5]
    if '.part' in name:
        continue
    data = json.load(open(path, encoding='utf-8'))
    table = {}
    for k, v in data.items():
        base, _, cat = k.partition('#')
        if base not in src or not isinstance(v, str) or not v.strip():
            continue
        table[src[base] + ('#' + cat if cat else '')] = v
    json.dump(table, open(os.path.join(dest, f'{name}.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0, sort_keys=True)
    print(name, len(table))
langs = sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(dest, '*.json')))
lines = ['/* Generated by tools/i18n/build.py: every translation file, loaded the first time its language is used. */',

         'export const LOCALES: Partial<Record<string, () => Record<string, string>>> = {']
lines += [f"  '{l}': () => require('./{l}.json')," for l in langs]
lines += ['};', '']
open(os.path.join(dest, 'index.ts'), 'w').write('\n'.join(lines))
print('languages:', ' '.join(langs))
