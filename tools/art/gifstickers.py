"""Honey & Tabby GIFs (docs/art/gifs) → animated stickers for every small pet picture in the app.
Usage (repo root): python3 tools/art/gifstickers.py
For each GIF writes
  assets/art/pets/<name>.webp        all frames side by side in one row (the app steps through them)
  assets/art/pets/still/<name>.png   one frame, for places that can't animate (widgets, Memory Cards, website)
and regenerates src/ui/petArt.generated.ts."""
import glob, json, os, sys
import cv2
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gifkit import SRC, frames  # noqa: E402

OUT = 'assets/art/pets'
FRAME = 384  # px per frame: crisp up to ~130 pt on a 3x screen, still light
# the frame shown where nothing animates: the most expressive pose of each GIF
STILL = {'dog_cheer': 0, 'dog_wave': 0, 'cat_wave': 3, 'dog_play': 3, 'cat_yarn': 0, 'duo_party': 0}

os.makedirs(f'{OUT}/still', exist_ok=True)
meta = {}
for path in sorted(glob.glob(f'{SRC}/*.gif')):
    name = os.path.splitext(os.path.basename(path))[0]
    fr, durs = frames(name)
    U = np.zeros(fr[0].shape[:2], bool)
    for f in fr:
        U |= f[:, :, 3] > 10
    ys, xs = np.where(U)
    cx, cy = (xs.min() + xs.max()) / 2, (ys.min() + ys.max()) / 2
    side = int(max(xs.max() - xs.min(), ys.max() - ys.min()) * 1.04) + 8
    x0, y0 = int(round(cx - side / 2)), int(round(cy - side / 2))
    cells = []
    for f in fr:
        pad = np.zeros((side, side, 4), np.uint8)
        sx0, sy0 = max(0, x0), max(0, y0)
        sx1, sy1 = min(f.shape[1], x0 + side), min(f.shape[0], y0 + side)
        pad[sy0 - y0:sy1 - y0, sx0 - x0:sx1 - x0] = f[sy0:sy1, sx0:sx1]
        cells.append(cv2.resize(pad, (FRAME, FRAME), interpolation=cv2.INTER_AREA))
    sheet = np.concatenate(cells, axis=1)
    Image.fromarray(sheet).save(f'{OUT}/{name}.webp', 'WEBP', quality=82, alpha_quality=88, method=6)
    still = cells[STILL.get(name, 0)]
    Image.fromarray(still).save(f'{OUT}/still/{name}.png', optimize=True)
    meta[name] = {'frames': len(fr), 'ms': int(round(float(np.mean(durs))))}
    print(name, len(fr), 'frames', os.path.getsize(f'{OUT}/{name}.webp') // 1024, 'KB', flush=True)

L = [
    '/* Generated by tools/art/gifstickers.py from docs/art/gifs. Do not edit by hand. */',
    '/** Every Honey & Tabby animation: one row of square frames, stepped every `ms`. `still` is one frame. */',
    'export const PET_ART = {',
]
for name, m in meta.items():
    L.append(f"  {name}: {{ sheet: require('../../assets/art/pets/{name}.webp'), still: require('../../assets/art/pets/still/{name}.png'), frames: {m['frames']}, ms: {m['ms']} }},")
L.append('} as const;')
L.append('')
L.append('export type PetArtName = keyof typeof PET_ART;')
L.append('')
open('src/ui/petArt.generated.ts', 'w').write('\n'.join(L))
