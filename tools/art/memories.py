"""Pavurio Memories card templates (ChatGPT, 2 Nov 2026) → assets/memories/<id>_<story|post>.png + manifest.

The owner's photos go *under* each template: its transparent openings are the photo slots. The layout
manifest is measured from the PNGs themselves (not typed by hand), so it always matches the art:
  - slots: every transparent opening (bbox + corner radius from the corner curve), in reading order;
  - title / footer: the widest clean white span inside the top and bottom pills, for the localized text.
Usage: python3 tools/art/memories.py <uploads_dir> <out_dir> <manifest_ts>"""
import json
import shutil
import sys
import numpy as np
from PIL import Image
from scipy import ndimage

TEMPLATES = [
    ('daily', 'f8548503', 'bbc039b9'),
    ('home', '2947db96', 'df83d2ec'),
    ('thennow', '129f9aec', '8de28054'),
    ('birthday', 'ae0210e3', 'e7495ece'),
    ('gotcha', 'b3280918', 'ccde0f0d'),
    ('adventures', '9e99b83a', 'afdeb7ca'),
    ('littlethings', 'ce8a6d5c', '02331598'),
    ('month', '2ff45164', '4b3da372'),
    ('bestfriend', '091e3523', '30fec950'),
    ('year', 'a1a027ed', 'b71f2d08'),
]

def corner_radius(mask, x0, y0, x1, y1):
    # first transparent pixel along the top-left diagonal: d = r (1 - 1/sqrt 2)
    for d in range(0, min(x1 - x0, y1 - y0) // 2):
        if mask[y0 + d, x0 + d]:
            return int(round(d / (1 - 2 ** -0.5)))
    return 0

def text_box(a, box):
    x0, y0, x1, y1 = box
    h = y1 - y0
    band = a[y0 + int(h * 0.22): y1 - int(h * 0.22), x0 + h // 2: x1 - h // 2]
    white = ((band[:, :, :3].min(axis=2) > 240) & (band[:, :, 3] > 240)).all(axis=0)
    best, cur, start = (0, 0), 0, 0
    for i, ok in enumerate(list(white) + [False]):
        if ok:
            if cur == 0:
                start = i
            cur += 1
        else:
            if cur > best[1] - best[0]:
                best = (start, start + cur)
            cur = 0
    pad = 14
    return {'x': x0 + h // 2 + best[0] + pad, 'y': y0 + int(h * 0.12), 'w': max(0, best[1] - best[0] - 2 * pad), 'h': int(h * 0.76)}

def measure(path):
    im = Image.open(path).convert('RGBA')
    a = np.array(im)
    W, H = im.size
    hole = a[:, :, 3] < 128
    lab, n = ndimage.label(hole)
    slots = []
    for i, sl in enumerate(ndimage.find_objects(lab)):
        if (lab[sl] == i + 1).sum() < 20000:
            continue
        y0, y1, x0, x1 = sl[0].start, sl[0].stop, sl[1].start, sl[1].stop
        slots.append({'x': x0, 'y': y0, 'w': x1 - x0, 'h': y1 - y0, 'r': corner_radius(lab == i + 1, x0, y0, x1, y1)})
    slots.sort(key=lambda s: (round(s['y'] / 40), s['x']))
    # pills: big opaque white blobs above / below the photos
    white = (a[:, :, :3].min(axis=2) > 245) & (a[:, :, 3] > 250)
    wl, _ = ndimage.label(white)
    pills = []
    for i, sl in enumerate(ndimage.find_objects(wl)):
        y0, y1, x0, x1 = sl[0].start, sl[0].stop, sl[1].start, sl[1].stop
        if x1 - x0 > W * 0.6 and 60 < y1 - y0 < 300:
            pills.append((x0, y0, x1, y1))
    top = min(pills, key=lambda b: b[1])
    bottom = max(pills, key=lambda b: b[1])
    return {'w': W, 'h': H, 'slots': slots, 'title': text_box(a, top), 'footer': text_box(a, bottom)}

src, out, ts = sys.argv[1], sys.argv[2], sys.argv[3]
manifest = {}
for tid, story, post in TEMPLATES:
    manifest[tid] = {}
    for fmt, key in (('story', story), ('post', post)):
        p = f'{src}/{key}-image.png'
        shutil.copyfile(p, f'{out}/{tid}_{fmt}.png')
        manifest[tid][fmt] = measure(p)
    print(tid, len(manifest[tid]['story']['slots']), manifest[tid]['story']['title'], manifest[tid]['story']['footer'])
json.dump(manifest, open(f'{out}/layout_manifest.json', 'w'), indent=1)
open(ts, 'w').write('// generated by tools/art/memories.py from the template PNGs — do not edit by hand\nexport const TEMPLATE_LAYOUT = ' + json.dumps(manifest) + ' as const;\n')
lines = ['// generated by tools/art/memories.py — do not edit by hand', 'export const TEMPLATE_ART = {']
for tid, _, _ in TEMPLATES:
    lines.append(f"  {tid}: {{ story: require('../../assets/memories/{tid}_story.png'), post: require('../../assets/memories/{tid}_post.png') }},")
lines.append('} as const;')
open(ts.replace('memoryTemplates.generated', 'memoryTemplateArt.generated'), 'w').write('\n'.join(lines) + '\n')
