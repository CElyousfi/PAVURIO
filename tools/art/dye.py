"""Split each clip's base coat (dog: honey, cat: tabby) into layers the app recolours at runtime, so a
new coat costs a few bytes in appearance.ts instead of a full set of sheets:
  fur_body  - alpha: the main coat area            (drawn tinted with the coat colour)
  fur_patch - alpha: patches / stripes             (drawn tinted with the patch colour)
  fur_shade - gray: fur shading, white = full tone (drawn over the fur with multiply)
  fur_feat  - rgba: everything that isn't fur      (outlines, eyes, nose, collar, props) drawn on top
Usage (repo root): python3 tools/art/dye.py dog   |   python3 tools/art/dye.py cat
Regenerates the matching src/animation/{dog,cat}Dye.ts asset map."""
import cv2, numpy as np, json, os, sys, glob, re
from PIL import Image

SPECIES = sys.argv[1] if len(sys.argv) > 1 else 'dog'
BASE = 'honey' if SPECIES == 'dog' else 'tabby'
DIR = f'assets/pets/{SPECIES}/clips'

def sm(x, a, b):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)

def layers(rgba):
    rgb = rgba[:, :, :3].astype(np.float32) / 255
    A = rgba[:, :, 3].astype(np.float32) / 255
    hsv = cv2.cvtColor(rgba[:, :, :3], cv2.COLOR_RGB2HSV).astype(np.float32)
    H, S, V = hsv[:, :, 0], hsv[:, :, 1] / 255, hsv[:, :, 2] / 255
    if SPECIES == 'dog':
        warm = sm(H, 2, 7) * (1 - sm(H, 34, 40))
        furish = warm * sm(V, 0.42, 0.6)
        # the bowl in the eat clip is a much more saturated orange than any fur: keep it as drawn
        prop = sm(S, 0.78, 0.86) * sm(V, 0.78, 0.86)
        furish = furish * (1 - prop)
        patch = sm(S, 0.28, 0.5) * furish
        body = (1 - sm(S, 0.28, 0.5)) * furish
        white = (1 - sm(S, 0.08, 0.16)) * sm(V, 0.8, 0.9) * (1 - warm)
        body = np.clip(body + white, 0, 1)
        Y = V
        ref_body, ref_patch = 0.98, 0.93
    else:
        chroma = rgb.max(2) - rgb.min(2)
        gray = 1 - sm(chroma, 0.07, 0.14)
        Y = 0.3 * rgb[:, :, 0] + 0.59 * rgb[:, :, 1] + 0.11 * rgb[:, :, 2]
        furish = gray * sm(Y, 0.24, 0.32) * (1 - sm(Y, 0.78, 0.86))
        patch = furish * (1 - sm(Y, 0.42, 0.55))
        body = furish * sm(Y, 0.42, 0.55)
        ref_body, ref_patch = 0.6, 0.42
    fur = np.clip(body + patch, 0, 1)
    shade = np.clip(np.where(patch > body, Y / ref_patch, Y / ref_body), 0, 1)
    a = lambda m: (np.clip(m * A, 0, 1) * 255).astype(np.uint8)
    white_rgb = np.full(rgb.shape, 255, np.uint8)
    body_l = np.dstack([white_rgb, a(body)])
    patch_l = np.dstack([white_rgb, a(patch)])
    g = (shade * 255).astype(np.uint8)
    shade_l = np.dstack([g, g, g, a(fur)])
    feat_l = np.dstack([rgba[:, :, :3], a(1 - fur)])
    return {'fur_body': body_l, 'fur_patch': patch_l, 'fur_shade': shade_l, 'fur_feat': feat_l}

manifest = json.load(open(f'{DIR}/clips.json'))
total = {}
for name, c in manifest.items():
    if name.startswith('_'):
        continue
    for ci in range(c['chunks']):
        src = np.array(Image.open(f'{DIR}/{name}_{BASE}_{ci}.webp').convert('RGBA'))
        for tag, im in layers(src).items():
            p = f'{DIR}/{name}_{tag}_{ci}.webp'
            # soft masks lose nothing at half size (the app stretches every sheet to the same box)
            scale, q, aq = {'fur_body': (0.5, 60, 50), 'fur_patch': (0.5, 60, 50), 'fur_shade': (0.6, 70, 60), 'fur_feat': (1.0, 78, 80)}[tag]
            img = Image.fromarray(im)
            if scale < 1:
                img = img.resize((int(img.width * scale), int(img.height * scale)), Image.LANCZOS)
            img.save(p, 'WEBP', quality=q, alpha_quality=aq, method=6)
            total[tag] = total.get(tag, 0) + os.path.getsize(p)
    print(name, flush=True)
print({k: f'{v/1e6:.1f}MB' for k, v in total.items()})

Cap = 'Dog' if SPECIES == 'dog' else 'Cat'
L = [f"/* Generated by tools/art/dye.py. Do not edit by hand. */", f"export const {SPECIES.upper()}_DYE: Record<string, Record<'fur_body' | 'fur_patch' | 'fur_shade' | 'fur_feat', number[]>> = {{"]
for name, c in manifest.items():
    if name.startswith('_'):
        continue
    L.append(f'  {name}: {{')
    for tag in ('fur_body', 'fur_patch', 'fur_shade', 'fur_feat'):
        L.append(f'    {tag}: [' + ', '.join(f"require('../../assets/pets/{SPECIES}/clips/{name}_{tag}_{i}.webp')" for i in range(c['chunks'])) + '],')
    L.append('  },')
L.append('};\n')
open(f'src/animation/{SPECIES}Dye.ts', 'w').write('\n'.join(L))
